/**
 * The character for a Martor emoji name (`rocket`, `-1`), or `undefined` for a
 * name Martor does not turn into an emoji.
 */
export const emojiForName = (name: string): Optional<string> =>
    Object.hasOwn(MARTOR_EMOJI, name) ? MARTOR_EMOJI[name] : undefined
