/**
 * Random UUIDv4 for wire-frame ids. Math.random is sufficient here: these ids
 * only correlate requests with responses on a single data channel and carry
 * no security weight.
 */
export const uuidv4 = (): string =>
    'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, c => {
        const r = (Math.random() * 16) | 0
        const v = c === 'x' ? r : (r & 0x3) | 0x8
        return v.toString(16)
    })
